#!/usr/bin/env node
/**
 * Builds config/hero-promo-videos.json — the clips the homepage hero plays.
 *
 * Source: the `videos` / `videoJobs` Firestore collections, i.e. the REAL
 * per-mix promo videos this pipeline generated (30s, artist + mix title),
 * not stock footage.
 *
 * Two things this script exists to enforce, both learned the hard way:
 *  1. Most stored URLs are SIGNED (GoogleAccessId/Expires/Signature). Those
 *     expire, and a permaweb page that outlives its own links is broken by
 *     construction. The signature is stripped and the bare object URL is kept.
 *  2. Not every object is publicly readable — some 403 without the signature.
 *     Each candidate is probed with a Range request and only entries that
 *     actually return 200/206 as video/* are written out.
 *
 * Re-run when new promos are generated:  node scripts/build-hero-promo-catalog.mjs
 */
import dotenv from 'dotenv';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

dotenv.config({ path: '.env.local' });
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(__dirname, '..', 'config', 'hero-promo-videos.json');

const { getFirestore } = await import('../lib/firebase-admin.js');
const db = getFirestore();

function bareUrl(u) {
  const i = u.indexOf('?');
  return i === -1 ? u : u.slice(0, i);
}

const candidates = new Map();
for (const coll of ['videos', 'videoJobs']) {
  const snap = await db.collection(coll).get();
  snap.forEach(d => {
    const v = d.data();
    const raw = v.videoUrl || (v.metadata && v.metadata.videoUrl);
    if (!raw) return;
    if (v.status && v.status !== 'completed') return;
    const url = bareUrl(raw);
    if (candidates.has(url)) return;
    const artist = v.artist || (v.metadata && v.metadata.artist) || '';
    const mixTitle = v.mixTitle || (v.metadata && v.metadata.mixTitle) || '';
    if (!artist || artist === 'random' || artist === '?') return;
    candidates.set(url, {
      url,
      artist,
      mixTitle: mixTitle && mixTitle !== 'Hitloop Video Remix' ? mixTitle : '',
      durationSec: Number(v.duration || (v.metadata && v.metadata.duration)) || null
    });
  });
}

console.log(`candidates from Firestore: ${candidates.size}`);

const kept = [];
for (const c of candidates.values()) {
  let ok = false, type = '';
  try {
    const res = await fetch(c.url, { headers: { Range: 'bytes=0-1023' } });
    type = res.headers.get('content-type') || '';
    ok = (res.status === 206 || res.status === 200) && /^video\//.test(type);
  } catch (err) { ok = false; }
  console.log(`${ok ? 'PUBLIC ' : 'skip   '} ${type.padEnd(12)} ${c.artist} — ${c.mixTitle || '(untitled)'}`);
  if (ok) kept.push(c);
}

/* One clip per mix. The pipeline has regenerated the same promo many times
   (hundreds of public objects across a few dozen mixes), and every URL emitted
   into the page costs bytes on a permaweb deploy — so dedupe on artist+title,
   keeping the first verified-public hit. Clips that don't name their mix are
   dropped: the hero uses the name to match the featured mix, and an unnamed
   clip can never win that match. */
const byMix = new Map();
for (const c of kept.filter(c => c.mixTitle)) {
  const key = (c.artist + '|' + c.mixTitle).toLowerCase();
  if (!byMix.has(key)) byMix.set(key, c);
}
kept.length = 0;
kept.push(...byMix.values());
kept.sort((a, b) => (a.artist + a.mixTitle).localeCompare(b.artist + b.mixTitle));
fs.writeFileSync(OUT, JSON.stringify({
  note: 'Generated by scripts/build-hero-promo-catalog.mjs — real per-mix promo videos, public URLs only (signatures stripped, access verified).',
  builtAt: new Date().toISOString(),
  clips: kept
}, null, 2) + '\n');
console.log(`\nwrote ${kept.length} public clips → config/hero-promo-videos.json`);
process.exit(0);
